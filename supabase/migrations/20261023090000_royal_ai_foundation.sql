-- Royal AI foundation for Store Royal.
-- This migration is intentionally isolated from checkout, orders, payments,
-- affiliates and the existing products table.
-- All client access is denied. Trusted Edge Functions use service_role.
BEGIN;

CREATE TABLE IF NOT EXISTS public.royal_ai_opportunities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  source_name text,
  source_url text,
  supplier_name text,
  supplier_url text,
  category text,
  image_url text,
  currency text NOT NULL DEFAULT 'BRL' CHECK (char_length(currency) = 3),
  supplier_cost numeric(12,2) CHECK (supplier_cost IS NULL OR supplier_cost >= 0),
  estimated_shipping numeric(12,2) CHECK (estimated_shipping IS NULL OR estimated_shipping >= 0),
  suggested_sale_price numeric(12,2) CHECK (suggested_sale_price IS NULL OR suggested_sale_price >= 0),
  estimated_margin numeric(12,2),
  estimated_margin_percent numeric(7,2),
  demand_score smallint CHECK (demand_score IS NULL OR demand_score BETWEEN 0 AND 100),
  competition_score smallint CHECK (competition_score IS NULL OR competition_score BETWEEN 0 AND 100),
  margin_score smallint CHECK (margin_score IS NULL OR margin_score BETWEEN 0 AND 100),
  supplier_score smallint CHECK (supplier_score IS NULL OR supplier_score BETWEEN 0 AND 100),
  royal_score smallint CHECK (royal_score IS NULL OR royal_score BETWEEN 0 AND 100),
  ai_summary text,
  ai_risks jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(ai_risks) = 'array'),
  raw_data jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(raw_data) = 'object'),
  status text NOT NULL DEFAULT 'discovered'
    CHECK (status IN ('discovered','reviewing','approved','rejected','published','archived')),
  reviewed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS royal_ai_opportunities_score_idx
  ON public.royal_ai_opportunities (royal_score DESC NULLS LAST, created_at DESC);
CREATE INDEX IF NOT EXISTS royal_ai_opportunities_status_idx
  ON public.royal_ai_opportunities (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.royal_ai_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  task_type text NOT NULL CHECK (char_length(btrim(task_type)) BETWEEN 1 AND 80),
  priority smallint NOT NULL DEFAULT 5 CHECK (priority BETWEEN 1 AND 10),
  status text NOT NULL DEFAULT 'queued'
    CHECK (status IN ('queued','processing','completed','failed','waiting_provider','cancelled')),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
  result jsonb,
  provider text,
  model text,
  attempts smallint NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  max_attempts smallint NOT NULL DEFAULT 5 CHECK (max_attempts BETWEEN 1 AND 20),
  available_at timestamptz NOT NULL DEFAULT now(),
  locked_at timestamptz,
  locked_by text,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS royal_ai_tasks_queue_idx
  ON public.royal_ai_tasks (status, priority DESC, available_at, created_at)
  WHERE status IN ('queued','waiting_provider');

CREATE TABLE IF NOT EXISTS public.royal_ai_providers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  provider_key text NOT NULL UNIQUE CHECK (provider_key ~ '^[a-z0-9_-]{2,50}$'),
  display_name text NOT NULL,
  priority smallint NOT NULL DEFAULT 100 CHECK (priority BETWEEN 1 AND 1000),
  enabled boolean NOT NULL DEFAULT true,
  free_only boolean NOT NULL DEFAULT true,
  model text,
  status text NOT NULL DEFAULT 'unknown'
    CHECK (status IN ('unknown','available','rate_limited','quota_exhausted','error','disabled')),
  cooldown_until timestamptz,
  consecutive_failures smallint NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
  last_success_at timestamptz,
  last_failure_at timestamptz,
  last_error_code text,
  last_error_message text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Provider rows contain routing state only. API keys must remain in Supabase secrets.
INSERT INTO public.royal_ai_providers (provider_key, display_name, priority, enabled, free_only)
VALUES
  ('gemini', 'Google Gemini', 10, true, true),
  ('groq', 'Groq', 20, true, true),
  ('local', 'Royal AI Local', 90, true, true)
ON CONFLICT (provider_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.royal_ai_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id uuid REFERENCES public.royal_ai_tasks(id) ON DELETE SET NULL,
  provider_key text,
  event_type text NOT NULL CHECK (char_length(btrim(event_type)) BETWEEN 1 AND 80),
  level text NOT NULL DEFAULT 'info' CHECK (level IN ('debug','info','warning','error')),
  message text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS royal_ai_logs_created_idx
  ON public.royal_ai_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS royal_ai_logs_task_idx
  ON public.royal_ai_logs (task_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.royal_ai_settings (
  id boolean PRIMARY KEY DEFAULT true CHECK (id = true),
  bootstrap_mode boolean NOT NULL DEFAULT true,
  allow_paid_providers boolean NOT NULL DEFAULT false,
  automation_enabled boolean NOT NULL DEFAULT false,
  max_concurrent_tasks smallint NOT NULL DEFAULT 1 CHECK (max_concurrent_tasks BETWEEN 1 AND 10),
  updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.royal_ai_settings (id, bootstrap_mode, allow_paid_providers, automation_enabled, max_concurrent_tasks)
VALUES (true, true, false, false, 1)
ON CONFLICT (id) DO NOTHING;

ALTER TABLE public.royal_ai_opportunities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.royal_ai_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.royal_ai_providers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.royal_ai_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.royal_ai_settings ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.royal_ai_opportunities FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.royal_ai_tasks FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.royal_ai_providers FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.royal_ai_logs FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.royal_ai_settings FROM PUBLIC, anon, authenticated;

GRANT ALL ON TABLE public.royal_ai_opportunities TO service_role;
GRANT ALL ON TABLE public.royal_ai_tasks TO service_role;
GRANT ALL ON TABLE public.royal_ai_providers TO service_role;
GRANT ALL ON TABLE public.royal_ai_logs TO service_role;
GRANT ALL ON TABLE public.royal_ai_settings TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.royal_ai_logs_id_seq TO service_role;

COMMENT ON TABLE public.royal_ai_opportunities IS
  'Radar Royal: oportunidades de produtos encontradas e avaliadas pela Royal AI.';
COMMENT ON TABLE public.royal_ai_tasks IS
  'Fila assíncrona da Royal AI; indisponibilidade de IA não bloqueia a Store Royal.';
COMMENT ON TABLE public.royal_ai_providers IS
  'Estado e prioridade dos provedores do AI Gateway. Nunca armazena chaves de API.';
COMMENT ON TABLE public.royal_ai_logs IS
  'Auditoria técnica da Royal AI sem armazenar segredos.';
COMMENT ON TABLE public.royal_ai_settings IS
  'Configuração global da Royal AI. Bootstrap começa em R$0 e bloqueia provedores pagos.';

COMMIT;